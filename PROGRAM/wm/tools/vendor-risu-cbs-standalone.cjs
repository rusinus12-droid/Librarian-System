'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { stripTypeScriptTypes } = require('node:module');

const ROOT = path.resolve(__dirname, '..');
const SOURCE_ROOT = path.resolve(process.argv[2] || path.join(ROOT, 'vendor', 'risu-cbs-standalone', 'src'));
const OUTPUT = path.join(ROOT, 'src', 'parts', '11-risu-cbs-parity-generated.js');
const FILES = ['scan.ts', 'calc.ts', 'evaluator.ts', 'candidates.ts', 'bridge.ts', 'runtime.ts'];

const stripModuleSyntax = (source) => stripTypeScriptTypes(source, { mode: 'transform' })
  .replace(/^\s*import[\s\S]*?from\s+["'][^"']+["'];\s*/gm, '')
  .replace(/^\s*import\s+["'][^"']+["'];\s*/gm, '')
  .replace(/\bexport\s+(?=(?:async\s+)?(?:function|const|let|var|class)\b)/g, '');

const chunks = [];
const sourceHashes = {};
for (const file of FILES) {
  const fullPath = path.join(SOURCE_ROOT, file);
  if (!fs.existsSync(fullPath)) throw new Error(`Missing vendored CBS source: ${fullPath}`);
  const source = fs.readFileSync(fullPath, 'utf8');
  sourceHashes[file] = crypto.createHash('sha256').update(source).digest('hex');
  chunks.push(`\n// ---- vendored ${file} ----\n${stripModuleSyntax(source).trim()}\n`);
}

let body = chunks.join('\n')
  .replaceAll('yumi_tr_cbs_candidates_v1', 'libra_cbs_candidates_v1')
  .replaceAll('yumi_tr_cbs_snapshot_v1', 'libra_cbs_snapshot_v1');
body = body.split('\n').map(line => `        ${line}`).join('\n');

const generated = [
  '    // Generated from the dependency-free risu-cbs-standalone reference implementation.',
  '    // Do not edit this file by hand; edit the vendored TypeScript and run tools/vendor-risu-cbs-standalone.cjs.',
  `    // Source hashes: ${JSON.stringify(sourceHashes)}`,
  '    const RisuCbsStandalone = (() => {',
  body,
  '        return Object.freeze({',
  '            evaluateRisuCbs, calculateRisuCbsString,',
  '            collectRisuCbsCandidates, createRisuCbsCandidateManifest,',
  '            readRisuCbsBridgeState, validateRisuCbsBridgeSnapshot, writeRisuCbsCandidateManifest,',
  '            buildRisuCbsRuntime, readRisuChatVariables,',
  '            RisuCbsBridgeRetryRequiredError,',
  '            RISU_CBS_CANDIDATES_KEY, RISU_CBS_SNAPSHOT_KEY',
  '        });',
  '    })();',
  '',
].join('\n');

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, generated, 'utf8');
console.log(JSON.stringify({ output: path.relative(ROOT, OUTPUT), bytes: Buffer.byteLength(generated), sourceHashes }, null, 2));

