'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const runtimePath = path.join(__dirname, 'libra_contract_runtime.cjs');
(async () => {
  assert.ok(fs.existsSync(runtimePath), 'explicit node contract runtime adapter exists');
  const original = require('./libra_playwright_loader.cjs');
  const load = mode => {
    if (mode === undefined) delete process.env.LIBRA_CONTRACT_RUNTIME;
    else process.env.LIBRA_CONTRACT_RUNTIME = mode;
    delete require.cache[runtimePath];
    return require(runtimePath);
  };
  assert.equal(load(undefined).loadPlaywright, original.loadPlaywright, 'default uses exact original Playwright loader');
  assert.equal(load('playwright').loadPlaywright, original.loadPlaywright, 'explicit playwright uses original loader');
  assert.throws(() => load('silent-fallback'), /Unsupported LIBRA_CONTRACT_RUNTIME/);
  const runtime = load('node');
  assert.equal(runtime.contractArtifactName(), 'LIBRA World Manager Full.js');
  process.env.LIBRA_CONTRACT_ARTIFACT = 'min';
  assert.equal(runtime.contractArtifactName(), 'LIBRA World Manager.js');
  process.env.LIBRA_CONTRACT_ARTIFACT = '../escape';
  assert.throws(() => runtime.contractArtifactName(), /Unsupported LIBRA_CONTRACT_ARTIFACT/);
  delete process.env.LIBRA_CONTRACT_ARTIFACT;
  const { chromium } = runtime.loadPlaywright();
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.setContent('<!doctype html><html lang="ko"><body><p id="sample">real DOM</p><script>window.unrequestedScript = true</script></body></html>');
  assert.equal(await page.evaluate(() => document.querySelector('#sample').textContent), 'real DOM');
  assert.equal(await page.evaluate(() => globalThis.unrequestedScript), undefined);
  assert.equal(await page.evaluate(() => typeof process + ':' + typeof require), 'undefined:undefined', 'callback executes in page realm');
  const outerValue = 19;
  await assert.rejects(page.evaluate(() => outerValue), /outerValue is not defined/, 'Node lexical closures must not leak into page');
  const argument = { nested: { x: 1 } };
  assert.deepEqual(await page.evaluate(arg => { arg.nested.x++; return { x: arg.nested.x, pageObject: arg instanceof Object }; }, argument), { x: 2, pageObject: true });
  assert.equal(argument.nested.x, 1, 'arguments cross by value');
  await page.addScriptTag({ content: 'globalThis.productFunction = n => n * 3;' });
  assert.equal(await page.evaluate(n => productFunction(n), 7), 21, 'script executes real function');
  assert.equal(await page.evaluate(async () => { await new Promise(resolve => setTimeout(resolve, 1)); return 31; }), 31);
  await page.evaluate(() => { globalThis.finished = false; setTimeout(() => { globalThis.finished = true; }, 10); });
  await page.waitForTimeout(25);
  assert.equal(await page.evaluate(() => finished), true, 'wait does not fake timer results');
  await assert.rejects(page.addScriptTag({ url: 'https://invalid.invalid/script.js' }), /Only inline script content/);
  await assert.rejects(page.evaluate('1 + 1'), /Only function callbacks/);
  const bad = await browser.newPage();
  await bad.setContent('<!doctype html>');
  await bad.addScriptTag({ content: 'Promise.reject(new Error("actual script failure"))' });
  await assert.rejects(bad.waitForTimeout(1), /actual script failure/);
  await assert.rejects(bad.close(), /actual script failure/);
  await browser.close();
  await assert.rejects(page.evaluate(() => true), /closed/);
  console.log(JSON.stringify({ ok: true, contract: 'explicit-node-adapter', checks: 'all adapter assertions passed' }));
})().catch(error => { console.error(error); process.exitCode = 1; });
