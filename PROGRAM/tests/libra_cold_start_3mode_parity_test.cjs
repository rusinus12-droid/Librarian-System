'use strict';
// Task 29 of Librarian-System-0.3.61-STORAGE-MODE-CONTINUATION-PLAN.md.
// LIBRA Manual Recovery / Cold Start (D7) — storage parity across the three modes.
//
// The repro `libra_failed_batch_fresh_retry_runtime_test.cjs` proves the recovery
// contract for plugin_only. Task 29 asks the same contract to hold in `mirror` and
// `server_only`: "server availability must never change the user's cold-start policy".
//
// Step 1 asserts, in all three modes:
//   1. no cold start happens automatically (the user must ask for it)
//   2. an explicit cold start creates exactly one fresh submission per batch
//   3. a retry of a failed batch creates a NEW run (fresh analysis, not a resume) and
//      clears inFlight without inheriting the parent operation budget
//   4. a successful canonical is never regenerated by a later cold start
//   5. reload/resume: the job head is durable and a resumed job is not a fresh one
//
// The LLM boundary is the only thing stubbed; the storage bridge, job store and
// canonical pipeline are the real ones.
const assert = require('node:assert/strict');
const { serverFixture, fiveMore } = require('./fixtures/libra_server_runtime_fixture.cjs');

const MODES = ['plugin_only', 'mirror', 'server_only'];

const parse = value => {
  if (value === null || value === undefined) return null;
  if (typeof value !== 'string') return value;
  try { return JSON.parse(value); } catch (_) { return null; }
};

// The canonical job head is an owner record: read it from whichever side owns it.
const readJobHead = (snapshot, mode) => {
  if (mode === 'plugin_only') {
    const key = [...snapshot.local.keys()].find(k => /canonical-job-head/.test(k));
    return key ? parse(snapshot.local.get(key)) : null;
  }
  const row = snapshot.storedRows().find(r => /canonical-job-head/.test(r.key));
  return row ? row.value : null;
};

async function waitFor(predicate, label, attempts = 1200) {
  for (let i = 0; i < attempts; i += 1) {
    if (await predicate()) return;
    await new Promise(resolve => setTimeout(resolve, 5));
  }
  throw new Error(`timeout waiting for ${label}`);
}

const readManifest = (snapshot, mode) => (mode === 'plugin_only'
  ? parse(snapshot.local.get([...snapshot.local.keys()].find(k => /:manifest$/.test(k))))
  : snapshot.getManifest());

async function coldStartPolicy(mode) {
  const snapshot = await serverFixture({ mode });
  try {
    const api = snapshot.f.r.api;

    // 1. Nothing runs on its own: the fixture's LLM stub counts real submissions.
    const callsBefore = snapshot.f.control.calls.length;

    // 2. Explicit cold start over the whole session.
    const job = await api.runManualColdStart({});
    assert.ok(job && typeof job === 'object', `${mode}: cold start must return a job`);

    const callsAfterColdStart = snapshot.f.control.calls.length;
    const head = readJobHead(snapshot, mode);
    const manifest = readManifest(snapshot, mode);
    const committedStarts = Object.keys(manifest?.memories || {}).map(Number).sort((a, b) => a - b);

    return {
      mode,
      automaticCallsBeforeUserAction: callsBefore,
      coldStartKind: String(job.kind || ''),
      coldStartState: String(job.state || ''),
      coldStartCompleted: Number(job.completed || 0),
      coldStartNewSubmissions: callsAfterColdStart - callsBefore,
      committedStarts,
      jobHeadPresent: !!head,
      jobHeadKind: String(head?.kind || ''),
      jobHeadState: String(head?.state || ''),
      inFlight: manifest?.inFlight ?? null
    };
  } finally {
    await snapshot.cleanup();
  }
}

// 4. A successful canonical must never be regenerated by a later cold start, and a
//    cold start with no new turns must not add submissions.
async function coldStartIdempotence(mode) {
  const snapshot = await serverFixture({ mode });
  try {
    const api = snapshot.f.r.api;
    await api.runManualColdStart({});
    const callsAfterFirst = snapshot.f.control.calls.length;
    const firstManifest = readManifest(snapshot, mode);
    const firstDigest = String(firstManifest?.memories?.['1']?.artifactDigest || '');

    const second = await api.runManualColdStart({});
    const callsAfterSecond = snapshot.f.control.calls.length;
    const secondManifest = readManifest(snapshot, mode);
    const secondDigest = String(secondManifest?.memories?.['1']?.artifactDigest || '');

    return {
      mode,
      firstDigest,
      secondDigest,
      submissionsFirstRun: callsAfterFirst,
      submissionsSecondRun: callsAfterSecond,
      secondRunCompleted: Number(second.completed || 0),
      secondRunSkipped: Number(second.skipped || 0)
    };
  } finally {
    await snapshot.cleanup();
  }
}

// 3 + 5. A failed batch retries as a NEW run (fresh analysis, not a resume), and the
//        canonical job record is durable across a plugin reload.
async function failedRetryAndResume(mode) {
  const snapshot = await serverFixture({ mode });
  try {
    const api = snapshot.f.r.api;
    const ownerRows = () => (mode === 'plugin_only'
      ? [...snapshot.local.entries()].map(([key, raw]) => ({ key, value: parse(raw) }))
      : snapshot.storedRows().map(row => ({ key: row.key, value: row.value })));
    const readRun = runId => ownerRows().find(row => row.key.endsWith(`:run:${runId}`))?.value || null;
    const readWork = start => ownerRows().find(row => row.key.endsWith(`:work:${start}`))?.value || null;

    // Force a real provider failure so the batch is recorded as failed.
    snapshot.f.control.modelFails = true;
    const failed = await api.runManualColdStart({});
    const ownerRowsAfterFailure = ownerRows();
    const failedRun = ownerRowsAfterFailure.find(row => /:run:/.test(row.key))?.value || null;
    const failedWork = ownerRowsAfterFailure.find(row => /:work:/.test(row.key))?.value || null;
    const failedMarker = readManifest(snapshot, mode)?.failedBatches?.['1'] || {};
    const failedRunId = String(failedRun?.runId || failedMarker.runId || '');
    const failedOperationId = String(failedRun?.providerBudget?.operationId || failedMarker.providerOperationId || '');

    // Retry the failed range explicitly — while the provider still fails, so the
    // retry must produce a NEW run identity rather than resume the first one.
    const callsBeforeRetry = snapshot.f.control.calls.length;
    const retried = await api.retryFailedMemoryAnalysis({ startTurns: [1] });
    const callsAfterRetry = snapshot.f.control.calls.length;

    const ownerRowsAfterRetry = ownerRows();
    const retryRun = ownerRowsAfterRetry.find(row => /:run:/.test(row.key))?.value || null;
    const retryWork = ownerRowsAfterRetry.find(row => /:work:/.test(row.key))?.value || null;
    const retryRunId = String(retryRun?.runId || '');
    const retryOperationId = String(retryRun?.providerBudget?.operationId || '');

    // 5. The job record must survive a plugin reload against the same storage.
    const headBeforeReload = readJobHead(snapshot, mode);
    await snapshot.restart();
    const headAfterReload = (mode === 'plugin_only'
      ? parse(snapshot.local.get([...snapshot.local.keys()].find(k => /canonical-job-head/.test(k))))
      : snapshot.storedRows().find(r => /canonical-job-head/.test(r.key))?.value) || null;

    return {
      mode,
      failureState: String(failed.state || ''),
      failureFailed: Number(failed.failed || 0),
      failedRunIdPresent: failedRunId.length > 0,
      failedOperationIdPresent: failedOperationId.length > 0,
      failedRunStatus: String(failedRun?.status || ''),
      failedWorkStatus: String(failedWork?.status || ''),
      // Where the failure is durably recorded: `plugin_only` keeps the manifest
      // marker; the server modes roll the manifest back (rejected-pointer CAS) and
      // record the failure on the run/work records instead.
      manifestFailedBatchMarker: Object.keys(failedMarker).length > 0,
      retryState: String(retried.state || ''),
      retriedFailed: Number(retried.failed || 0),
      retrySubmissions: callsAfterRetry - callsBeforeRetry,
      retryIsNewRun: retryRunId !== failedRunId && retryRunId.length > 0,
      retryIsNewOperation: retryOperationId !== failedOperationId && retryOperationId.length > 0,
      retryRunHasNoParent: retryRun?.retry === undefined,
      discardedFailedRunAbsent: !ownerRowsAfterRetry.some(row => row.key.endsWith(`:run:${failedRunId}`)),
      retryWorkStatus: String(retryWork?.status || ''),
      retryWorkRunIdMatches: String(retryWork?.runId || '') === retryRunId,
      inFlightAfterRetry: readManifest(snapshot, mode)?.inFlight ?? null,
      headJobIdBeforeReload: String(headBeforeReload?.jobId || ''),
      headJobIdAfterReload: String(headAfterReload?.jobId || '')
    };
  } finally {
    await snapshot.cleanup();
  }
}

(async () => {
  const policies = [];
  const idempotence = [];
  const recovery = [];
  for (const mode of MODES) {
    policies.push(await coldStartPolicy(mode));
    idempotence.push(await coldStartIdempotence(mode));
    recovery.push(await failedRetryAndResume(mode));
  }
  console.log(JSON.stringify({ policies, idempotence, recovery }, null, 1));

  // 1. No cold start may run before the user asks for one.
  for (const p of policies) {
    assert.equal(p.automaticCallsBeforeUserAction, 0,
      `${p.mode}: no canonical analysis may run before the user starts a cold start`);
    assert.equal(p.coldStartState, 'completed',
      `${p.mode}: the explicit cold start must complete (state='${p.coldStartState}')`);
    assert.equal(p.coldStartCompleted, 1,
      `${p.mode}: the explicit cold start must commit the one eligible batch`);
    assert.ok(p.coldStartNewSubmissions >= 1,
      `${p.mode}: the explicit cold start must perform real analysis submissions`);
    assert.equal(p.inFlight, null,
      `${p.mode}: a completed cold start must leave no in-flight run`);
  }

  // Cross-mode: the cold start outcome must not depend on where the data lives.
  const [firstPolicy, ...restPolicies] = policies;
  for (const p of restPolicies) {
    assert.deepEqual(p.committedStarts, firstPolicy.committedStarts,
      `${p.mode}: committed canonical batches must match ${firstPolicy.mode}`);
    assert.equal(p.coldStartKind, firstPolicy.coldStartKind,
      `${p.mode}: the cold-start job kind must not depend on the storage mode`);
  }

  // 4. A successful canonical must not be regenerated by a later cold start.
  for (const run of idempotence) {
    assert.ok(run.firstDigest.length > 0, `${run.mode}: the first cold start must commit a canonical`);
    assert.equal(run.secondDigest, run.firstDigest,
      `${run.mode}: a second cold start must not regenerate a successful canonical`);
    assert.equal(run.submissionsSecondRun, run.submissionsFirstRun,
      `${run.mode}: a cold start with no new complete batch must add no analysis submissions`);
  }

  // 3 + 5. A failed batch retries as a NEW run, and the job head survives a reload.
  for (const r of recovery) {
    assert.equal(r.failureFailed, 1,
      `${r.mode}: a terminal provider failure must fail the batch (state='${r.failureState}')`);
    // The failure identity is durable in every mode — recorded on the run/work
    // records (`plugin_only` additionally keeps the manifest `failedBatches` marker;
    // the server modes roll the manifest back through the rejected-pointer CAS).
    assert.equal(r.failedRunStatus, 'failed',
      `${r.mode}: the failed run must be recorded as failed`);
    assert.equal(r.failedWorkStatus, 'failed',
      `${r.mode}: the failed work record must be recorded as failed`);
    assert.ok(r.failedRunIdPresent,
      `${r.mode}: the failure must carry a durable run id`);
    assert.ok(r.failedOperationIdPresent,
      `${r.mode}: the failure must carry a durable provider operation id`);
    assert.ok(r.retryIsNewRun,
      `${r.mode}: an explicit retry must create a NEW run, not resume the failed one`);
    assert.ok(r.retryIsNewOperation,
      `${r.mode}: an explicit retry must create a new provider operation budget`);
    assert.equal(r.retryRunHasNoParent, true,
      `${r.mode}: the fresh analysis must not inherit the parent operation`);
    assert.equal(r.discardedFailedRunAbsent, true,
      `${r.mode}: the discarded failed run must be physically absent`);
    assert.ok(r.retrySubmissions >= 1,
      `${r.mode}: the explicit retry must perform a fresh analysis submission`);
    assert.equal(r.retryWorkRunIdMatches, true,
      `${r.mode}: the work record must point at the retried run`);
    assert.equal(r.inFlightAfterRetry, null,
      `${r.mode}: a terminal failure is not crash-resumable in-flight work`);
    assert.ok(r.headJobIdBeforeReload.length > 0, `${r.mode}: the canonical job head must be recorded`);
    assert.equal(r.headJobIdAfterReload, r.headJobIdBeforeReload,
      `${r.mode}: the canonical job head must survive a plugin reload`);
  }

  // The manifest marker location is mode-specific BY DESIGN: plugin_only keeps it in
  // the manifest, the server modes roll the manifest back and rely on the run/work
  // records. A mode silently losing BOTH would be the defect.
  for (const r of recovery) {
    const hasAnyFailureRecord = r.manifestFailedBatchMarker || (r.failedRunStatus === 'failed' && r.failedWorkStatus === 'failed');
    assert.equal(hasAnyFailureRecord, true,
      `${r.mode}: a failed batch must leave a durable failure record somewhere`);
  }

  // Cross-mode: the recovery identity rules must not depend on the storage mode.
  const [firstRecovery, ...restRecovery] = recovery;
  for (const r of restRecovery) {
    assert.equal(r.retryIsNewRun, firstRecovery.retryIsNewRun,
      `${r.mode}: the retry-as-new-run rule must match ${firstRecovery.mode}`);
    assert.equal(r.discardedFailedRunAbsent, firstRecovery.discardedFailedRunAbsent,
      `${r.mode}: the discarded-run rule must match ${firstRecovery.mode}`);
  }

  process.stdout.write('libra_cold_start_3mode_parity_test: PASS\n');
})().catch(error => {
  process.stderr.write(`${error.stack || error}\n`);
  process.exitCode = 1;
});
