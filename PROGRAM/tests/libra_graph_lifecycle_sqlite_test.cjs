'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path'),crypto=require('node:crypto');
const {createMemorySuiteServer}=require('../server/server.cjs');
const create=require('../server/core/libra-graph-lifecycle.cjs');
const hash=x=>crypto.createHash('sha256').update(x).digest('hex');
test('two independent SQLite owners fence publication, live readers, expired tokens and root-reachable deletion',async t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'libra-graph-lifecycle-'));
 const a=createMemorySuiteServer({dataDir:dir,autoBackup:false,port:0}),b=createMemorySuiteServer({dataDir:dir,autoBackup:false,port:0});
 t.after(async()=>{await b.close();await a.close();fs.rmSync(dir,{recursive:true,force:true});});
 const one=a.repositories.libra,two=b.repositories.libra;let clock=Date.now();
 const adapter=repo=>create({namespace:'libra',get:repo.get,list:repo.list,applyConditionalBatch:repo.applyConditionalBatch,now:()=>clock});
 const x=adapter(one),y=adapter(two),scopeKey='real-gc',prefix='libra:v1:scope:'+scopeKey+':memory-graph:v1:';
 const cmd=(owner,action,data={})=>owner.command({scopeKey,action,...data});
 const build=cmd(x,'acquire',{kind:'build'});
 assert.throws(()=>cmd(y,'acquire',{kind:'gc'}),/NAMESPACE_BUSY/);
 const put=(repo,key,value,graphLease=null)=>repo.mutate({kind:'set',space:'plugin',key,value,operationId:'fixture-'+crypto.randomUUID(),graphLease});
 const page=prefix+'corpus:page:directory:'+hash('page');put(one,page,'[]');
 const manifestRaw=JSON.stringify({schema:'libra.graph_corpus.v1',refs:[{key:page}],sourceProofs:{}}),manifest=prefix+'corpus:manifest:'+hash(manifestRaw);put(one,manifest,manifestRaw);
 const root=prefix+'corpus:root:'+hash('root'),rootRaw=JSON.stringify({schema:'libra.graph_corpus.v1',manifestKey:manifest,digest:hash(manifestRaw)});
 assert.throws(()=>put(two,root,rootRaw),/LEASE_EXPIRED/);
 put(one,root,rootRaw,{scopeKey,token:build.token});cmd(x,'release',{token:build.token});
 const reader=cmd(y,'acquire',{kind:'read'});assert.throws(()=>cmd(x,'acquire',{kind:'gc'}),/NAMESPACE_BUSY/);
 const orphan=prefix+'corpus:page:directory:'+hash('orphan');put(one,orphan,'[]');
 clock+=60001;const gc=cmd(x,'acquire',{kind:'gc'});
 assert.throws(()=>cmd(y,'assert',{token:reader.token}),/LEASE_EXPIRED/);
 assert.throws(()=>put(two,prefix+'page:units:'+hash('late'),'[]'),/NAMESPACE_BUSY/);
 assert.throws(()=>cmd(y,'acquire',{kind:'read'}),/NAMESPACE_BUSY/);
 const inventory=cmd(x,'inventory',{token:gc.token});assert.ok(inventory.retainedKeys.includes(page));
 const candidate=key=>inventory.records.find(row=>row.key===key);
 assert.throws(()=>cmd(x,'delete',{token:gc.token,candidate:candidate(page)}),/KEY_REACHABLE/);
 assert.equal(one.get('plugin',page).exists,true);
 assert.equal(cmd(x,'delete',{token:gc.token,candidate:candidate(orphan)}).deleted,true);
 assert.equal(two.get('plugin',orphan).tombstone,true);
 assert.ok(!cmd(x,'inventory',{token:gc.token}).records.some(row=>row.key===orphan),'retired tombstones do not consume the live inventory admission');
 assert.throws(()=>cmd(x,'delete',{token:gc.token,candidate:{...candidate(page),key:'libra:v1:scope:real-gc:manifest'}}),/KEY_UNOWNED/);
 clock+=60001;const replacement=cmd(y,'acquire',{kind:'gc'});
 assert.throws(()=>cmd(x,'delete',{token:gc.token,candidate:candidate(page)}),/LEASE_EXPIRED/);
 cmd(y,'release',{token:replacement.token});
 const resumed=cmd(y,'acquire',{kind:'read',requestId:'idempotent-reader'});
 assert.equal(cmd(y,'acquire',{kind:'read',requestId:'idempotent-reader'}).token,resumed.token);
 cmd(y,'release',{token:resumed.token});
 assert.throws(()=>put(two,'libra:v1:scope:'+scopeKey+':memory-graph-control:v1:root',{schema:'libra.graph_lifecycle.v1',leases:[]}),/CONTROL_WRITE_FORBIDDEN/);
 const late=cmd(x,'acquire',{kind:'build'}),badRaw=JSON.stringify({schema:'libra.graph_corpus.v1',refs:[{key:orphan}]});
 const badManifest=prefix+'corpus:manifest:'+hash(badRaw);put(one,badManifest,badRaw);
 assert.throws(()=>put(one,prefix+'corpus:root:late',JSON.stringify({schema:'libra.graph_corpus.v1',manifestKey:badManifest,digest:hash(badRaw)}),{scopeKey,token:late.token}),/ROOT_REFERENCE_MISSING/);
 cmd(x,'release',{token:late.token});
 // A separate Node process opens its own SQLite connection, not a mock owner.
 const script="const {createMemorySuiteServer}=require(process.argv[1]);const app=createMemorySuiteServer({dataDir:process.argv[2],autoBackup:false,port:0});const owner=app.repositories.libra.graphLifecycle;const scopeKey=process.argv[3];const lease=owner.command({scopeKey,action:'acquire',kind:'read'});process.send({ready:true});process.once('message',async()=>{owner.command({scopeKey,action:'release',token:lease.token});await app.close();process.send({released:true});process.disconnect();});";
 const child=require('node:child_process').spawn(process.execPath,['-e',script,path.resolve(__dirname,'../server/server.cjs'),dir,scopeKey],{stdio:['ignore','ignore','pipe','ipc']});
 t.after(()=>{if(child.exitCode===null)child.kill();});
 const message=()=>new Promise((resolve,reject)=>{child.once('message',resolve);child.once('error',reject);});
 assert.equal((await message()).ready,true);
 assert.throws(()=>one.graphLifecycle.command({scopeKey,action:'acquire',kind:'gc'}),/NAMESPACE_BUSY/);
 const released=message();child.send('release');assert.equal((await released).released,true);
 const final=one.graphLifecycle.command({scopeKey,action:'acquire',kind:'gc'});one.graphLifecycle.command({scopeKey,action:'release',token:final.token});
});
