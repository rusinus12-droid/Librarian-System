'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert/strict');
const source=fs.readFileSync(path.join(__dirname,'../plugins/LIBRA.js'),'utf8');
const start=source.indexOf('  const BOOK_NARRATIVE_GROUPS ='),end=source.indexOf('  const bookNarrativeHistoryKey =',start);
const events=[{turn:7,text:'다음 날 출발했다.'},{turn:6,text:'마을에 도착했다.'},{turn:6,text:'지도를 찾았다.'},{turn:6,text:'숙소를 정했다.'},{text:'날짜 미상 기록 하나'},{text:'날짜 미상 기록 둘'}];
const before=JSON.stringify(events);
const c=vm.createContext({inputEvents:events,worldManagerSnapshotView:()=>({narrative:{events}}),guiAsObject:x=>x||{},guiAsArray:x=>Array.isArray(x)?x:[],text:x=>String(x??''),compact:(x,n)=>String(x??'').slice(0,n),buildBookBrowse:x=>x,guiEl:(tag,props,children)=>({tag,...props,children}),bookDomainFreshness:()=>null});
vm.runInContext(source.slice(start,end)+'\nglobalThis.render=()=>bookNarrativeModel({narrative:{events:inputEvents}});',c);
const result=c.render(),t6=result.events.filter(x=>x.turn===6);
assert.equal(t6.length,1);assert.equal(t6[0].rows.length,3);
assert.equal(result.events.filter(x=>x.turn===7).length,1);
assert.equal(result.events.filter(x=>x.turn===0).length,2);
assert(t6[0].title.includes('마을에 도착했다.'));
assert(t6[0].rows.some(r=>r.text.includes('숙소를 정했다.')),'group includes every event');
const detail=JSON.stringify(t6[0].rows);
for(const e of events.filter(e=>e.turn===6))assert(detail.includes(e.text));
assert(!detail.includes('다음 날 출발했다.'));
assert.equal(JSON.stringify(events),before,'projection does not mutate stored events');
console.log('PASS narrative turn grouping, complete detail/search, stable first-entry title, unknown turns, immutable source');
