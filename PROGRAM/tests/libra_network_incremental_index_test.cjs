'use strict';
const assert = require('node:assert/strict');
const create = require('../tools/libra_memory_network.cjs');
const frame = {owner:'plugin:owner',scopeKey:'scope',worldlineId:'main',asOf:null,authorityEpoch:1,activeSourceMapping:'1'};
const item = (id, token, n=1) => ({id, fingerprint:`${id}:${n}`, postings:{token:[token],entity:[],predicate:[],time:[]}, dependencies:[`source:${id}`], vector:[n,0]});
const network = create({hash: s => s.length});
assert.equal(typeof network.createPagedIndex, 'function', 'A2 must expose owner-bound paged incremental postings');
const index = network.createPagedIndex({pageSize:7});
const rows = Array.from({length:150},(_,i)=>item(`id${i}`,`token${i}`));
index.reconcile({frame, revision:1, items:rows});
assert.equal(index.inspect().coverage.indexed,150);
const baseline = index.inspect().io;
index.reconcile({frame, revision:1, trustedRevision:true});
assert.equal(index.inspect().io.metadataRows,baseline.metadataRows,'trusted unchanged revision needs no metadata reconstruction');
const pagesBefore=index.inspect().io.pagesRead;
const firstCommon=index.query({tokens:rows.map((_,i)=>`token${i}`)});
assert.equal(firstCommon.ids.length,7);
assert.ok(index.inspect().io.pagesRead-pagesBefore<=7,'first result page must not read every posting page');
const queries = rows.map((_,i)=>`token${i}`);
let cursor, ids=[];
do { const page=index.query({tokens:queries,cursor}); ids.push(...page.ids);cursor=page.cursor; } while(cursor);
assert.equal(ids.length,150,'all tokens beyond 64 and oldest rows must be reachable through paging');
assert.deepEqual(ids,rows.map(r=>r.id));
assert.equal(index.scanDense([1,0]).vectorsScanned,150);
assert.equal(index.scanDense([1,0]).dotTerms,300);
assert.equal(index.inspect().bytes.packedVectors,Math.ceil(150/7)*7*2*8);
// Delta must prove the preceding owner revision; append additionally needs prefix proof.
assert.throws(()=>index.reconcile({frame,revision:2,trustedRevision:true,fromRevision:0,verifiedChangedIDs:true,items:[item('id0','edited',2)],changedIDs:['id0']}),/DELTA_UNVERIFIED/);
assert.throws(()=>index.reconcile({frame,revision:2,trustedRevision:true,fromRevision:1,verifiedChangedIDs:true,items:[item('new','appended')],changedIDs:['new'],append:true}),/PREFIX_UNVERIFIED/);
index.reconcile({frame,revision:2,trustedRevision:true,fromRevision:1,verifiedChangedIDs:true,items:[item('id0','edited',2)],changedIDs:['id0'],deletedIDs:['id1']});
assert.deepEqual(index.query({tokens:['token0','token1']}).ids,[]);
assert.deepEqual(index.query({tokens:['edited']}).ids,['id0']);
assert.equal(index.inspect().coverage.indexed,149);
index.reconcile({frame,revision:3,trustedRevision:true,fromRevision:2,verifiedChangedIDs:true,items:[item('new','appended')],changedIDs:['new'],append:true,prefixVerified:true});
assert.deepEqual(index.query({tokens:['appended']}).ids,['new']);
const stale=index.query({tokens:queries}).cursor;
index.reconcile({frame,revision:4,items:[item('new','appended'),item('id0','edited',2)]});
assert.throws(()=>index.query({tokens:queries,cursor:stale}),/CURSOR_STALE/);
assert.deepEqual(index.query({tokens:['edited','appended']}).ids,['new','id0'],'reorder must update canonical tie order');
index.invalidateDependencies(['source:new']);
assert.equal(index.inspect().coverage.status,'partial','invalidated dependency requires owner refresh');
assert.throws(()=>index.reconcile({frame,revision:4,trustedRevision:true}),/DELTA_UNVERIFIED/);
assert.deepEqual(index.query({tokens:['appended']}).ids,[]);
assert.throws(()=>index.query({tokens:[],frame:{...frame,owner:'other'}}),/OWNER_MISMATCH/);
index.reconcile({frame:{...frame,owner:'other'},revision:1,items:[item('other','other')]});
assert.deepEqual(index.query({tokens:['edited']}).ids,[],'owner swap cannot retain old postings');
const fallback=index.inspect().io.fallbacks;
index.reconcile({frame:{...frame,owner:'other'},revision:1,items:[item('other','other')]});
assert.equal(index.inspect().io.fallbacks,fallback+1);
assert.equal(index.inspect().coverage.status,'complete','fully traversed fallback is complete coverage despite linear cost');
assert.equal(index.inspect().io.lastFallbackReason,'owner_revision_unavailable');
const invalidDelta=network.createPagedIndex();
invalidDelta.reconcile({frame,revision:1,items:[item('a','a'),item('b','b')]});
assert.throws(()=>invalidDelta.reconcile({frame,revision:2,fromRevision:1,trustedRevision:true,verifiedChangedIDs:true,changedIDs:['a','a'],items:[item('a','A'),item('b','B')]}),/DELTA_UNVERIFIED/);
assert.deepEqual(invalidDelta.query({tokens:['a','b']}).ids,['a','b']);
const wide=network.createPagedIndex();
wide.reconcile({frame,revision:1,items:[{...item('wide','wide'),vector:Array(256).fill(.123456789)}]});
assert.ok(wide.inspect().bytes.exactMetadata<1024,'packed vectors must not also retain their full decimal JSON representation');
(async()=>{
 const paged=network.createPagedIndex({pageSize:7});
 assert.equal(typeof paged.reconcilePaged,'function','runtime cold/fallback preparation must cooperate with request cancellation');
 let yields=0,checkpoints=0;
 await paged.reconcilePaged({frame,revision:1,items:rows},{checkpoint:()=>checkpoints++,yieldPage:async()=>yields++});
 assert.ok(yields>20);assert.ok(checkpoints>yields);
 assert.equal(paged.inspect().coverage.indexed,150);
 const interrupted=network.createPagedIndex({pageSize:7});let visits=0;
 await assert.rejects(interrupted.reconcilePaged({frame,revision:1,items:rows},{checkpoint:()=>{if(++visits===24)throw new Error('request_cancelled');},yieldPage:async()=>{}}),/request_cancelled/);
 assert.equal(interrupted.inspect().coverage.status,'partial','cancelled mutation cannot publish complete coverage');
 assert.ok(interrupted.inspect().coverage.indexed<150);
 interrupted.reconcile({frame,revision:1,items:rows});assert.equal(interrupted.inspect().coverage.status,'complete');
 console.log('libra_network_incremental_index_test: PASS');
})().catch(error=>{console.error(error.stack);process.exitCode=1;});
